#!/usr/bin/env python3
"""
Automated ParaView and PyVista visualization pipeline for WAKE CFD.
Loads VTK XML ImageData (.vti) files, computes Q-criterion vortex core
isosurfaces, generates stream tracers, and produces 3D renderings.
"""

import os
import sys
import argparse

def render_pyvista(vti_file, output_image, isovalue=0.001):
    try:
        import pyvista as pv
    except ImportError:
        print("[WAKE PARAVIEW] PyVista not installed; cannot render 3D offscreen view.")
        print(f"To view {vti_file}, open it directly in ParaView or run: pip install pyvista")
        return False

    pv.set_plot_theme("document")
    grid = pv.read(vti_file)

    plotter = pv.Plotter(off_screen=True)

    # 1. Volume rendering of Speed
    if "Speed" in grid.point_data:
        plotter.add_volume(grid, scalars="Speed", cmap="viridis", opacity="sigmoid_5", show_scalar_bar=True)

    # 2. Q-criterion isosurface for coherent turbulent vortex cores
    if "Q_Criterion" in grid.point_data:
        try:
            contours = grid.contour([isovalue], scalars="Q_Criterion")
            plotter.add_mesh(contours, color="#00ffcc", opacity=0.75, specular=0.5, label="Q-Criterion Core")
        except Exception as e:
            print(f"[WAKE PARAVIEW] Isosurface extraction notice: {e}")

    # 3. Solid obstacle representation
    if "CellType" in grid.point_data:
        try:
            solids = grid.threshold([1, 2], scalars="CellType")
            plotter.add_mesh(solids, color="#555555", opacity=1.0)
        except Exception:
            pass

    plotter.camera_position = 'iso'
    plotter.screenshot(output_image)
    print(f"[WAKE PARAVIEW] Saved 3D visualization to: {output_image}")
    return True

def generate_paraview_state_script(vti_file, output_python_script):
    """
    Generates a standalone pvpython script for ParaView batch processing.
    """
    script_content = f"""# ParaView batch pipeline script generated by WAKE CFD
from paraview.simple import *

reader = XMLImageDataReader(FileName=['{os.path.abspath(vti_file)}'])
view = GetActiveViewOrCreate('RenderView')

# Display velocity magnitude
display = Show(reader, view)
display.ColorArrayName = ['POINTS', 'Speed']

# Contour filter for Q-criterion vortex tubes
contour = Contour(Input=reader)
contour.ContourBy = ['POINTS', 'Q_Criterion']
contour.Isosurfaces = [0.001]
contour_display = Show(contour, view)
contour_display.DiffuseColor = [0.0, 0.8, 0.9]

Render()
SaveScreenshot('paraview_render.png', view, ImageResolution=[1920, 1080])
print('Saved ParaView render to paraview_render.png')
"""
    with open(output_python_script, 'w') as f:
        f.write(script_content)
    print(f"[WAKE PARAVIEW] Generated ParaView batch script: {output_python_script}")

def main():
    parser = argparse.ArgumentParser(description="ParaView/PyVista pipeline for WAKE CFD")
    parser.add_argument("input_vti", type=str, help="Input .vti file")
    parser.add_argument("--out", type=str, default="wake_paraview_render.png", help="Output render image")
    parser.add_argument("--iso", type=float, default=0.001, help="Q-criterion isovalue")
    parser.add_argument("--gen-pvpython", type=str, default=None, help="Generate ParaView pvpython script")
    args = parser.parse_args()

    if not os.path.exists(args.input_vti):
        print(f"Error: File not found: {args.input_vti}")
        sys.exit(1)

    if args.gen_pvpython:
        generate_paraview_state_script(args.input_vti, args.gen_pvpython)
    else:
        render_pyvista(args.input_vti, args.out, args.iso)

if __name__ == "__main__":
    main()
